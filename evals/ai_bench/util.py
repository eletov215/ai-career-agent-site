from __future__ import annotations

import hashlib
import json
import re
from pathlib import Path
from typing import Any, Iterable

_SAFE_IDENTIFIER_KEYS = {"run_id", "fingerprint", "config_fingerprint", "response_sha256", "dataset_fingerprint"}

_SECRET_PATTERNS = (
    re.compile(r"(?i)(authorization\s*[:=]\s*bearer\s+)[^\s,;]+"),
    re.compile(r"(?i)(api[_-]?key\s*[:=]\s*)[^\s,;]+"),
    re.compile(r"(?i)(token\s*[:=]\s*)[^\s,;]+"),
    re.compile(r"\bsk-[A-Za-z0-9_-]{12,}\b"),
    re.compile(r"\b[A-Za-z0-9_-]{32,}\b"),
)


def utc_now_iso() -> str:
    from datetime import datetime, timezone

    return datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")


def canonical_json(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))


def sha256_text(value: str) -> str:
    return hashlib.sha256(value.encode("utf-8")).hexdigest()


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def redact_secrets(value: Any) -> Any:
    if isinstance(value, dict):
        clean: dict[str, Any] = {}
        for key, item in value.items():
            lowered = str(key).lower()
            secret_key = (
                "api_key" in lowered
                or "apikey" in lowered
                or "authorization" in lowered
                or "secret" in lowered
                or lowered == "token"
                or lowered.endswith("_token")
                or lowered in {"access_token", "refresh_token", "id_token"}
            )
            if secret_key:
                clean[str(key)] = "[REDACTED]"
            elif lowered in _SAFE_IDENTIFIER_KEYS and isinstance(item, str):
                # These values are generated by the benchmark itself and are evidence identifiers,
                # not credentials. Preserve them so two runs can be compared reproducibly.
                clean[str(key)] = item
            else:
                clean[str(key)] = redact_secrets(item)
        return clean
    if isinstance(value, list):
        return [redact_secrets(item) for item in value]
    if isinstance(value, tuple):
        return [redact_secrets(item) for item in value]
    if isinstance(value, str):
        result = value
        for pattern in _SECRET_PATTERNS:
            if pattern.groups:
                result = pattern.sub(lambda match: f"{match.group(1)}[REDACTED]", result)
            else:
                result = pattern.sub("[REDACTED]", result)
        return result
    return value


def flatten_text(value: Any) -> str:
    parts: list[str] = []

    def visit(item: Any) -> None:
        if isinstance(item, dict):
            for key, child in item.items():
                parts.append(str(key))
                visit(child)
        elif isinstance(item, (list, tuple)):
            for child in item:
                visit(child)
        elif item is not None:
            parts.append(str(item))

    visit(value)
    return "\n".join(parts)


def normalize_text(value: str) -> str:
    value = value.casefold().replace("ё", "е")
    value = re.sub(r"[^\w%+.#/-]+", " ", value, flags=re.UNICODE)
    return re.sub(r"\s+", " ", value).strip()


def get_path(value: Any, dotted_path: str) -> tuple[bool, Any]:
    current = value
    if dotted_path in ("", "$"):
        return True, current
    path = dotted_path[2:] if dotted_path.startswith("$.") else dotted_path
    for segment in path.split("."):
        if isinstance(current, dict) and segment in current:
            current = current[segment]
        else:
            return False, None
    return True, current


def iter_paths(value: Any, prefix: str = "$") -> Iterable[tuple[str, Any]]:
    yield prefix, value
    if isinstance(value, dict):
        for key, item in value.items():
            yield from iter_paths(item, f"{prefix}.{key}")
    elif isinstance(value, list):
        for index, item in enumerate(value):
            yield from iter_paths(item, f"{prefix}[{index}]")


def iter_path_pattern(value: Any, pattern: str) -> Iterable[tuple[str, Any]]:
    """Yield values for the small JSONPath subset used by benchmark contracts.

    Supported syntax: ``$.name``, ``$.items[*].text`` and nested combinations.
    This deliberately avoids a runtime JSONPath dependency.
    """
    if pattern == "$":
        yield "$", value
        return
    if not pattern.startswith("$."):
        return
    raw_segments = pattern[2:].split(".")
    nodes: list[tuple[str, Any]] = [("$", value)]
    for raw in raw_segments:
        wildcard = raw.endswith("[*]")
        key = raw[:-3] if wildcard else raw
        next_nodes: list[tuple[str, Any]] = []
        for path, node in nodes:
            if not isinstance(node, dict) or key not in node:
                continue
            child = node[key]
            child_path = f"{path}.{key}"
            if wildcard:
                if not isinstance(child, list):
                    continue
                next_nodes.extend((f"{child_path}[{index}]", item) for index, item in enumerate(child))
            else:
                next_nodes.append((child_path, child))
        nodes = next_nodes
    yield from nodes
